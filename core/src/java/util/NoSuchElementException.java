package java.util;

public class NoSuchElementException extends java.lang.RuntimeException {
    public NoSuchElementException() { super(); }
    public NoSuchElementException(String m) { super(m); }
    public NoSuchElementException(String m, Throwable c) { super(m, c); }
    public NoSuchElementException(Throwable c) { super(c); }
}
