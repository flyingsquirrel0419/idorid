package java.io;

public class UncheckedIOException extends java.lang.RuntimeException {
    public UncheckedIOException() { super(); }
    public UncheckedIOException(String m) { super(m); }
    public UncheckedIOException(String m, Throwable c) { super(m, c); }
    public UncheckedIOException(Throwable c) { super(c); }
}
